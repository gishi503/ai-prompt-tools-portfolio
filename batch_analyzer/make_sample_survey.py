OTHER = [
    "駐車場がもう少し広いと嬉しいです。",
    "駅から近くて便利です。",
    "特になし。",
    "",
]
AGES = ["10代", "20代", "30代", "40代", "50代以上"]
WEIGHTS = {"接客": 18, "味・メニュー": 22, "価格": 14, "待ち時間": 16, "店内の雰囲気": 12, "清潔さ": 8, "Wi-Fi・電源": 6}


def main(n: int = 100, seed: int = 7):
    rng = random.Random(seed)
    topics = list(WEIGHTS)
    rows = []
    for i in range(1, n + 1):
        if rng.random() < 0.05:
            text = rng.choice(OTHER)
        else:
            first = rng.choices(topics, weights=[WEIGHTS[t] for t in topics])[0]
            text = rng.choice(VOICES[first])
            if rng.random() < 0.25:  # 2つの内容に触れている回答も混ぜる
                second = rng.choice([t for t in topics if t != first])
                text += rng.choice(VOICES[second])
        rows.append({"id": i, "年代": rng.choice(AGES), "回答": text})

    out = Path(__file__).parent / "samples" / "cafe_survey.csv"
    out.parent.mkdir(exist_ok=True)
    with open(out, "w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["id", "年代", "回答"])
        writer.writeheader()
        writer.writerows(rows)
    print(f"{out} に{len(rows)}件を書き出しました")


if __name__ == "__main__":
    main()
